type WikiIconName = keyof typeof feather.icons;

function WikiIcon({ name, size = 16 }: { name: WikiIconName; size?: number }) {
  const markup = feather.icons[name].toSvg({
    width: size,
    height: size,
    "stroke-width": 1.8,
    "aria-hidden": "true",
  });
  return (
    <span
      className="icon"
      aria-hidden="true"
      dangerouslySetInnerHTML={{ __html: markup }}
    />
  );
}

function Code({ children }: { children: string }) {
  return (
    <pre className="wiki-code">
      <code>{children}</code>
    </pre>
  );
}

function Note({ children }: { children: ReactNode }) {
  return (
    <aside className="wiki-note">
      <WikiIcon name="info" />
      <div>{children}</div>
    </aside>
  );
}

