const levels: WikiLevel[] = ["Start here", "Methods", "Advanced", "Reference"];

export function TrainingWiki() {
  const [query, setQuery] = useState("");
  const [contentsOpen, setContentsOpen] = useState(true);
  const [readingMode, setReadingMode] = useState<"page" | "continuous">("page");
  const [activeEntryId, setActiveEntryId] = useState(wikiEntries[0].id);
  const articlesRef = useRef<HTMLDivElement>(null);
  const entryLinksRef = useRef<Record<string, HTMLAnchorElement | null>>({});
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  const filtered = useMemo(
    () =>
      wikiEntries.filter((entry) => {
        const haystack =
          `${entry.title} ${entry.summary} ${entry.search}`.toLocaleLowerCase();
        return terms.every((term) => haystack.includes(term));
      }),
    [query],
  );
  const activeIndex = Math.max(
    0,
    filtered.findIndex((entry) => entry.id === activeEntryId),
  );
  const activeEntry = filtered[activeIndex];

  function selectEntry(entryId: string) {
    setActiveEntryId(entryId);
    requestAnimationFrame(() => {
      entryLinksRef.current[entryId]?.scrollIntoView({
        behavior: "smooth",
        block: "nearest",
      });
      articlesRef.current?.scrollIntoView({
        behavior: "smooth",
        block: "start",
      });
    });
  }

  function movePage(offset: number) {
    const next = filtered[activeIndex + offset];
    if (next) selectEntry(next.id);
  }

  return (
    <div className="wiki-view">
      <div className="wiki-search-dock">
        <span className="wiki-title-tag">
          <WikiIcon name="book-open" />
          Ai Training Wiki
        </span>
        <label className="wiki-search">
          <WikiIcon name="search" />
          <input
            type="search"
            value={query}
            placeholder="Search methods, data, or settings"
            aria-label="Search the training wiki"
            autoComplete="off"
            spellCheck={false}
            onChange={(event) => setQuery(event.target.value)}
            onKeyDown={(event) => {
              if (event.key === "Escape") setQuery("");
            }}
          />
          {query && (
            <button
              type="button"
              aria-label="Clear wiki search"
              title="Clear search"
              onClick={() => setQuery("")}
            >
              <WikiIcon name="x" size={15} />
            </button>
          )}
        </label>
        <span aria-hidden="true" />
      </div>

      <div
        className={`wiki-layout ${contentsOpen ? "" : "contents-collapsed"}`}
      >
        <aside className="wiki-tool-rail" aria-label="Wiki view controls">
          <button
            type="button"
            className={contentsOpen ? "active" : undefined}
            aria-label={contentsOpen ? "Hide contents" : "Show contents"}
            title={contentsOpen ? "Hide contents" : "Show contents"}
            onClick={() => setContentsOpen((open) => !open)}
          >
            <WikiIcon name="sidebar" />
          </button>
          <span aria-hidden="true" />
          <button
            type="button"
            className={readingMode === "continuous" ? "active" : undefined}
            aria-label={
              readingMode === "page"
                ? "Use continuous scrolling"
                : "Use page mode"
            }
            title={
              readingMode === "page" ? "Continuous scrolling" : "Page mode"
            }
            onClick={() =>
              setReadingMode((mode) =>
                mode === "page" ? "continuous" : "page",
              )
            }
          >
            <WikiIcon
              name={readingMode === "page" ? "align-justify" : "book-open"}
            />
          </button>
          {readingMode === "page" && filtered.length > 0 && (
            <>
              <span aria-hidden="true" />
              <button
                type="button"
                aria-label="Previous wiki article"
                title="Previous article"
                disabled={activeIndex === 0}
                onClick={() => movePage(-1)}
              >
                <WikiIcon name="chevron-up" />
              </button>
              <button
                type="button"
                aria-label="Next wiki article"
                title="Next article"
                disabled={activeIndex === filtered.length - 1}
                onClick={() => movePage(1)}
              >
                <WikiIcon name="chevron-down" />
              </button>
            </>
          )}
        </aside>

        {contentsOpen && (
          <nav className="wiki-toc" aria-label="Wiki table of contents">
            <div className="wiki-toc-heading">
              <h2>Contents</h2>
              <p>
                {query
                  ? `${filtered.length} of ${wikiEntries.length} articles`
                  : `${wikiEntries.length} articles`}
              </p>
            </div>
            <div className="wiki-toc-scroll">
              {levels.map((level) => {
                const entries = filtered.filter(
                  (entry) => entry.level === level,
                );
                if (!entries.length) return null;
                return (
                  <section key={level}>
                    <h3>{level}</h3>
                    {entries.map((entry) => (
                      <a
                        key={entry.id}
                        href={`#wiki-${entry.id}`}
                        ref={(link) => {
                          entryLinksRef.current[entry.id] = link;
                        }}
                        className={
                          readingMode === "page" && entry.id === activeEntry?.id
                            ? "active"
                            : undefined
                        }
                        aria-current={
                          readingMode === "page" && entry.id === activeEntry?.id
                            ? "page"
                            : undefined
                        }
                        onClick={(event) => {
                          if (readingMode === "page") {
                            event.preventDefault();
                            selectEntry(entry.id);
                          } else {
                            setActiveEntryId(entry.id);
                          }
                        }}
                      >
                        {entry.title}
                      </a>
                    ))}
                  </section>
                );
              })}
            </div>
          </nav>
        )}

        <div
          className="wiki-articles"
          role="region"
          aria-label="Wiki articles"
          tabIndex={-1}
          ref={articlesRef}
        >
          {filtered.length ? (
            (readingMode === "page" && activeEntry
              ? [activeEntry]
              : filtered
            ).map((entry) => (
              <article id={`wiki-${entry.id}`} key={entry.id}>
                <header>
                  <span>{entry.level}</span>
                  <h2>{entry.title}</h2>
                  <p>{entry.summary}</p>
                </header>
                <div className="wiki-article-body">{entry.content}</div>
                {readingMode === "page" && (
                  <nav className="wiki-page-navigation" aria-label="Wiki pages">
                    <button
                      type="button"
                      disabled={activeIndex === 0}
                      onClick={() => movePage(-1)}
                    >
                      <WikiIcon name="arrow-left" />
                      Previous
                    </button>
                    <span>
                      Article {activeIndex + 1} of {filtered.length}
                    </span>
                    <button
                      type="button"
                      disabled={activeIndex === filtered.length - 1}
                      onClick={() => movePage(1)}
                    >
                      Next
                      <WikiIcon name="arrow-right" />
                    </button>
                  </nav>
                )}
              </article>
            ))
          ) : (
            <section className="wiki-empty-search">
              <WikiIcon name="search" size={24} />
              <h2>No matching article</h2>
              <p>
                Try a method name such as DPO or GRPO, a data field such as
                reward, or a training control such as batch size.
              </p>
              <button type="button" onClick={() => setQuery("")}>
                Clear search
              </button>
            </section>
          )}
        </div>
      </div>
    </div>
  );
}
